"""robin CLI.

  robin route "<request>"          which agent + skills would handle it
  robin agents | skills            list the org
  robin validate                   check agent/skill files
  robin registry                   regenerate org/REGISTRY.md (compact catalogue)
  robin eval routing               routing accuracy on evals/routing/cases.yaml (free, offline)
  robin ask "<request>"            run a task (needs Anthropic credentials)
  robin trace <task-id>            show a task's trace
  robin kb lint|index|stale        knowledge checks / regenerate indexes / list stale nodes
  robin kb query [--near ID] [--hops N] [--market X] [--type T] [--text "..."]
  robin kb new ID TYPE "summary"   create a node
  robin kb add-source URL GRADE "summary" < excerpt.txt
  robin kb add-fact ID "fact" SRC[,SRC] GRADE [--inferred]
  robin kb gap "question" [--tried ...] [--next ...]
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def _print(lines):
    for line in lines:
        print(line)


def cmd_route(a):
    from robin.router import Router
    r = Router().route(a.request)
    print(f"agent: {r.agent}" + ("" if r.confident else "  (low confidence -> chief-of-staff asks)"))
    _print(f"  {m.name:28} score={m.score:<6} conf={m.confidence}" for m in r.agents)
    print("skills:")
    _print(f"  {m.name:28} score={m.score:<6} conf={m.confidence}" for m in r.skills)


def cmd_agents(a):
    from robin.registry import load_agents
    for ag in load_agents().values():
        print(f"{ag.name:24} {ag.kind:10} {ag.tier:8} {ag.sensitivity:10} skills={','.join(ag.skills)}")


def cmd_skills(a):
    from robin.registry import load_skills
    for s in load_skills().values():
        print(f"{s.name:26} {s.department:18} {s.description[:90]}")


def cmd_validate(a):
    from robin.registry import validate
    errors = validate()
    _print(errors)
    print(f"registry: {'OK' if not errors else f'{len(errors)} problem(s)'}")
    return 1 if errors else 0


def cmd_registry(a):
    from robin.registry import load_agents, load_skills
    agents, skills = load_agents(), load_skills()
    lines = ["<!-- generated by `robin registry` — do not edit by hand -->", "# Registry",
             "", "Who does what. Read this instead of opening every agent file.", "", "## Agents", "",
             "agent | dept | use for | skills", "---|---|---|---"]
    for ag in agents.values():
        use = ag.description.split(". ")[0].replace("|", "/")
        lines.append(f"{ag.name} | {ag.department} | {use} | {', '.join(ag.skills)}")
    lines += ["", "## Skills", "", "skill | dept | use when", "---|---|---"]
    for s in skills.values():
        lines.append(f"{s.name} | {s.department} | {s.description.split('Use when')[-1].strip().replace('|', '/')[:160]}")
    (ROOT / "org" / "REGISTRY.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"org/REGISTRY.md: {len(agents)} agents, {len(skills)} skills")


def cmd_eval(a):
    import yaml
    from robin.router import Router
    if a.suite == "process":
        return _eval_process(a)
    if a.suite != "routing":
        print("suites: routing (offline, free) | process (live, costs money)")
        return 2
    cases = yaml.safe_load((ROOT / "evals" / "routing" / f"{a.set}.yaml").read_text())["cases"]
    # focus set = active departments only (config/org.yaml); other sets measure the full catalogue.
    router = Router(active=True if a.set == "focus" else None)
    ok_agent = ok_skill = 0
    misses = []
    for c in cases:
        r = router.route(c["request"])
        agent_ok = r.agent == c["agent"]
        skill_ok = "skill" not in c or c["skill"] in [m.name for m in r.skills[:3]]
        ok_agent += agent_ok
        ok_skill += skill_ok
        if not (agent_ok and skill_ok):
            misses.append(f"  MISS {c['request'][:60]!r}: got {r.agent}/{[m.name for m in r.skills[:3]]}, "
                          f"want {c['agent']}/{c.get('skill', '-')}")
    n = len(cases)
    _print(misses)
    print(f"routing eval [{a.set}]: agent {ok_agent}/{n} ({ok_agent / n:.0%}), skill in top-3 {ok_skill}/{n} ({ok_skill / n:.0%})")
    return 0 if ok_agent / n >= a.threshold and ok_skill / n >= a.threshold else 1


def _eval_process(a):
    import yaml
    from evals.process.checks import CHECKS
    from robin.orchestrator import run_sync
    cases = yaml.safe_load((ROOT / "evals" / "process" / "cases.yaml").read_text())["cases"]
    if a.only:
        cases = [c for c in cases if c["id"] in a.only.split(",")]
    passed, cost = 0, 0.0
    for c in cases:
        res = run_sync(c["request"])
        cost += res.get("cost_usd", 0)
        results = [CHECKS[name](res["output"], trace_tools=res.get("tools"), **(c.get("args") or {}))
                   for name in c["checks"]]
        ok = all(r[0] for r in results)
        passed += ok
        print(f"{'PASS' if ok else 'FAIL'} {c['id']} [{res['task']}] " + "; ".join(r[1] for r in results))
    print(f"process evals: {passed}/{len(cases)} pass · cost ${cost:.4f}")
    return 0 if passed == len(cases) else 1


def cmd_ask(a):
    from robin.orchestrator import run_sync
    res = run_sync(a.request)
    print(res["output"])
    print(f"\n[{res['task']} · ${res.get('cost_usd', 0):.4f} · {res.get('words', 0)} words · route {res.get('route', {}).get('agent')}]",
          file=sys.stderr)


def cmd_trace(a):
    from robin import trace
    recs = trace.read(a.task_id)
    if not recs:
        print(f"no trace for {a.task_id}")
        return 1
    for r in recs:
        print(json.dumps(r, ensure_ascii=False, default=str))


def cmd_kb(a):
    from robin.kb import index, lint, query, writer
    if a.kb_cmd == "lint":
        errors = lint.lint()
        _print(errors)
        print(f"kb lint: {'OK' if not errors else f'{len(errors)} problem(s)'}")
        return 1 if errors else 0
    if a.kb_cmd == "index":
        print(json.dumps(index.build()))
    elif a.kb_cmd == "stale":
        _print(query.stale() or ["nothing stale"])
    elif a.kb_cmd == "query":
        _print(query.query(near=a.near, hops=a.hops, market=a.market, type_=a.type, text=a.text,
                           limit=a.limit, include_stale=a.include_stale) or ["no match"])
    elif a.kb_cmd == "new":
        print(writer.create_node(a.id, a.type, a.summary, markets=a.markets.split(",") if a.markets else None,
                                 by=a.by, commit=a.commit))
    elif a.kb_cmd == "add-source":
        print(writer.add_source(a.url, sys.stdin.read(), a.grade, a.summary, by=a.by, commit=a.commit))
    elif a.kb_cmd == "add-fact":
        writer.add_fact(a.id, a.fact, a.sources.split(","), a.grade, inferred=a.inferred, by=a.by,
                        task=a.task, commit=a.commit)
        print("ok")
    elif a.kb_cmd == "gap":
        writer.add_gap(a.question, a.tried, a.next, by=a.by)
        print("ok")


def main(argv=None) -> int:
    p = argparse.ArgumentParser(prog="robin", description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("route"); s.add_argument("request"); s.set_defaults(fn=cmd_route)
    sub.add_parser("agents").set_defaults(fn=cmd_agents)
    sub.add_parser("skills").set_defaults(fn=cmd_skills)
    sub.add_parser("validate").set_defaults(fn=cmd_validate)
    sub.add_parser("registry").set_defaults(fn=cmd_registry)
    s = sub.add_parser("eval"); s.add_argument("suite"); s.add_argument("--threshold", type=float, default=0.85)
    s.add_argument("--set", default="cases", help="cases (tuning set) or holdout")
    s.add_argument("--only", help="process eval ids, comma-separated")
    s.set_defaults(fn=cmd_eval)
    s = sub.add_parser("ask"); s.add_argument("request"); s.set_defaults(fn=cmd_ask)
    s = sub.add_parser("trace"); s.add_argument("task_id"); s.set_defaults(fn=cmd_trace)

    kb = sub.add_parser("kb"); kb.set_defaults(fn=cmd_kb)
    ks = kb.add_subparsers(dest="kb_cmd", required=True)
    ks.add_parser("lint"); ks.add_parser("index"); ks.add_parser("stale")
    q = ks.add_parser("query")
    q.add_argument("--near"); q.add_argument("--hops", type=int, default=1); q.add_argument("--market")
    q.add_argument("--type"); q.add_argument("--text"); q.add_argument("--limit", type=int, default=10)
    q.add_argument("--include-stale", action="store_true")
    for name in ("new", "add-source", "add-fact", "gap"):
        x = ks.add_parser(name)
        x.add_argument("--by", default="robin")
        if name != "gap":
            x.add_argument("--commit", action="store_true")
        if name == "new":
            x.add_argument("id"); x.add_argument("type"); x.add_argument("summary"); x.add_argument("--markets")
        elif name == "add-source":
            x.add_argument("url"); x.add_argument("grade"); x.add_argument("summary")
        elif name == "add-fact":
            x.add_argument("id"); x.add_argument("fact"); x.add_argument("sources"); x.add_argument("grade")
            x.add_argument("--inferred", action="store_true"); x.add_argument("--task", default="")
        else:
            x.add_argument("question"); x.add_argument("--tried", default=""); x.add_argument("--next", default="")

    a = p.parse_args(argv)
    return a.fn(a) or 0


if __name__ == "__main__":
    sys.exit(main())
