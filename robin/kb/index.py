"""kb index — regenerate domain _index.md files and graph.json; flip expired nodes to stale.

Generated files are committed so a cold agent can read them without running
anything; the pre-commit hook regenerates them (DECISIONS.md D-007).
"""
from __future__ import annotations

import datetime as dt
import json

from robin import frontmatter
from robin.kb import schema
from robin.kb.schema import KB

HEADER = "<!-- generated by `robin kb index` — do not edit by hand -->"


def flip_expired(today: dt.date | None = None) -> list[str]:
    flipped = []
    for nid, n in schema.load_all().items():
        if n.meta.get("status") == "active" and n.expired(today):
            n.meta["status"] = "stale"
            n.path.write_text(frontmatter.dump(n.meta, n.body), encoding="utf-8")
            flipped.append(nid)
    return flipped


def build(today: dt.date | None = None) -> dict:
    flipped = flip_expired(today)
    nodes = schema.load_all()
    by_domain: dict[str, list] = {}
    for n in nodes.values():
        if n.type == "source":
            continue
        top = n.path.relative_to(KB).parts[0]
        by_domain.setdefault(top, []).append(n)

    for domain, items in by_domain.items():
        if domain.startswith("_"):
            continue
        lines = [HEADER, f"# {domain}", "", "id | status | updated | summary", "---|---|---|---"]
        for n in sorted(items, key=lambda n: n.id):
            m = n.meta
            lines.append(f"[[{n.id}]] | {m.get('status')} | {m.get('updated')} | {m.get('summary', '')}")
        (KB / domain / "_index.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    graph = {
        "nodes": [
            {"id": n.id, "type": n.type, "status": n.meta.get("status"), "markets": n.meta.get("markets", []),
             "updated": str(n.meta.get("updated")), "summary": n.meta.get("summary", "")}
            for n in sorted(nodes.values(), key=lambda n: n.id)
        ],
        "edges": [
            {"from": n.id, "edge": e.edge, "to": e.target, "note": e.note}
            for n in sorted(nodes.values(), key=lambda n: n.id) for e in n.edges
        ] + [
            {"from": s, "edge": "evidence_for", "to": n.id, "note": ""}
            for n in sorted(nodes.values(), key=lambda n: n.id) for s in (n.meta.get("sources") or [])
        ],
    }
    (KB / "graph.json").write_text(json.dumps(graph, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    return {"nodes": len(graph["nodes"]), "edges": len(graph["edges"]), "flipped_to_stale": flipped}
